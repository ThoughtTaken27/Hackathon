"""Deterministic synthetic alarm sounds for testing a smoke/CO alarm pattern detector (safety-alert evaluation).

synth(kind, seed, snr_db) builds 10 s of 16 kHz audio: an alarm pattern mixed into household background at a
chosen SNR. Kinds: t3 (smoke alarm, NFPA 72 temporal-3: three 0.5 s beeps, 0.5 s gaps, 1.5 s off), t4 (CO alarm:
four 100 ms beeps, 100 ms gaps, 5 s off), timer (3-5 kitchen-timer beeps, irregular spacing, then silence) and
none (background only). Background = pink noise, plus (when present) a random benign ESC-50 household clip from
data/clips/esc50_all, plus a synthetic room echo on half the seeds. The same (kind, seed, snr) always gives the same
audio, so audio is never saved. main() embeds 60 seeds x 4 kinds x 4 SNRs with frozen CED-tiny and caches
results/cache/ced-tiny_synth_alarms.npz. Everything here is synthetic, generated by our own code.
ESC-50 background clips: K. J. Piczak 2015, CC BY-NC 3.0.

Run: python -m eval.synth_alarms
"""
from __future__ import annotations

import time
from pathlib import Path

import numpy as np
import soundfile as sf

from eval.offlist import pink

ROOT = Path(__file__).resolve().parents[1]
CLIPS = ROOT / "data" / "clips" / "esc50_all"
CACHE = ROOT / "results" / "cache" / "ced-tiny_synth_alarms.npz"
BENIGN = ["pouring_water", "washing_machine", "vacuum_cleaner", "keyboard_typing", "footsteps", "clock_tick", "water_drops"]
KINDS = ["t3", "t4", "timer", "none"]
SNRS = [20, 10, 0, -5]
SEEDS = 60


def _beep(freq: float, dur: float, sr: int) -> np.ndarray:
    """Sine beep with 5 ms fades so edges do not click."""
    t = np.arange(int(dur * sr)) / sr
    y = np.sin(2 * np.pi * freq * t)
    n = min(int(0.005 * sr), len(y) // 2)
    y[:n] *= np.linspace(0, 1, n)
    y[len(y) - n:] *= np.linspace(1, 0, n)
    return y.astype(np.float32)


def _cycle(kind: str, rng, sr: int) -> np.ndarray:
    """One repeating cycle of the alarm pattern (beeps and silence)."""
    f = rng.uniform(2900, 3300)
    parts: list[np.ndarray] = []
    if kind == "t3":
        for _ in range(3):
            parts += [_beep(f, 0.5, sr), np.zeros(int(0.5 * sr), np.float32)]
        parts.append(np.zeros(int(1.0 * sr), np.float32))  # 0.5 gap after 3rd beep + 1.0 = 1.5 s off
    elif kind == "t4":
        for _ in range(4):
            parts += [_beep(f, 0.1, sr), np.zeros(int(0.1 * sr), np.float32)]
        parts.append(np.zeros(int(4.8 * sr), np.float32))  # 0.1 gap + 4.8 = 5 s off after last beep
    else:  # timer
        f = rng.uniform(1000, 2500)
        for _ in range(int(rng.integers(3, 6))):
            parts += [_beep(f, rng.uniform(0.2, 0.3), sr), np.zeros(int(rng.uniform(0.1, 0.6) * sr), np.float32)]
        parts.append(np.zeros(int(rng.uniform(3, 6) * sr), np.float32))
    return np.concatenate(parts)


def _alarm(kind: str, rng, sr: int, n: int) -> np.ndarray:
    """Alarm track of length n with a random start phase inside the cycle."""
    if kind == "none":
        return np.zeros(n, np.float32)
    cyc = _cycle(kind, rng, sr)
    tiled = np.tile(cyc, int(np.ceil((n + len(cyc)) / len(cyc))))
    start = int(rng.integers(0, len(cyc)))
    return tiled[start:start + n]


def _echo(x: np.ndarray, rng, sr: int) -> np.ndarray:
    """Convolve with an exponentially decaying noise impulse response (RT60 0.2-0.6 s)."""
    rt60 = rng.uniform(0.2, 0.6)
    t = np.arange(int(rt60 * sr)) / sr
    ir = rng.standard_normal(len(t)) * 10 ** (-3 * t / rt60)  # -60 dB at t = rt60
    ir[0] = 1.0
    from scipy.signal import fftconvolve
    return fftconvolve(x, ir / np.abs(ir).sum() * 4, mode="full")[:len(x)].astype(np.float32)


def _background(rng, sr: int, n: int) -> np.ndarray:
    """Pink noise, plus a random benign ESC-50 household clip when available."""
    bg = pink(n, rng)
    files = sorted(p for c in BENIGN for p in CLIPS.glob(f"esc50_{c}_*.flac"))
    if files and rng.random() < 0.7:
        x, fsr = sf.read(files[int(rng.integers(len(files)))], dtype="float32")
        x = np.tile(x, int(np.ceil(n / len(x))))[:n]
        bg = bg * 0.3 + x / (np.abs(x).max() + 1e-9) * 0.5
    return bg.astype(np.float32)


def synth(kind: str, seed: int, snr_db: float, sr: int = 16000, seconds: int = 10) -> np.ndarray:
    """Deterministic alarm-in-background audio at the given SNR, peak-normalised to -30..-6 dBFS."""
    if kind not in KINDS:
        raise ValueError(f"unknown kind {kind!r}")
    rng = np.random.default_rng([seed, KINDS.index(kind), int(snr_db) + 100])
    n = sr * seconds
    bg = _background(rng, sr, n)
    sig = _alarm(kind, rng, sr, n)
    if seed % 2 == 1:
        bg, sig = _echo(bg, rng, sr), _echo(sig, rng, sr) if sig.any() else sig
    if kind != "none":
        on = sig != 0
        p_sig = np.mean(sig[on] ** 2) if on.any() else 1.0
        p_bg = np.mean(bg ** 2) + 1e-12
        sig = sig * np.sqrt(p_bg / p_sig * 10 ** (snr_db / 10))  # SNR measured while the alarm is sounding
    y = bg + sig
    peak_db = rng.uniform(-30, -6)
    return (y / (np.abs(y).max() + 1e-12) * 10 ** (peak_db / 20)).astype(np.float32)


def main() -> None:
    from kettle import encoders
    t0 = time.time()
    meta = [(k, s, snr) for k in KINDS for snr in SNRS for s in range(SEEDS)]
    waves = np.stack([synth(k, s, snr) for k, s, snr in meta])
    enc = encoders.load()
    embs, scores = [], []
    for i in range(0, len(waves), 32):
        e, sc = encoders.embed(enc, waves[i:i + 32])
        embs.append(e), scores.append(sc)
    np.savez_compressed(CACHE, files=np.array([f"{k}_s{s}_snr{snr}" for k, s, snr in meta]), kind=np.array([m[0] for m in meta]),
                        seed=np.array([m[1] for m in meta]), snr=np.array([m[2] for m in meta]),
                        emb=np.concatenate(embs).astype(np.float16), scores=np.concatenate(scores).astype(np.float16),
                        rms_db=np.array([20 * np.log10(np.sqrt(np.mean(w ** 2)) + 1e-12) for w in waves], np.float32))
    print({"clips": len(meta), "cache": str(CACHE.relative_to(ROOT)), "seconds": round(time.time() - t0)})


if __name__ == "__main__":
    main()
